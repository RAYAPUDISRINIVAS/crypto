from django.core.management.base import BaseCommand

from Keyapp.db import get_connection


SCHEMA_STATEMENTS = (
    """
    CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username VARCHAR(100) NOT NULL UNIQUE,
        password_hash VARCHAR(255) NOT NULL,
        contact_no VARCHAR(20),
        email VARCHAR(120),
        address VARCHAR(255),
        role VARCHAR(20) NOT NULL DEFAULT 'user',
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS user_keys (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username VARCHAR(100) NOT NULL,
        key_version INTEGER NOT NULL,
        wrapped_key TEXT NOT NULL,
        is_active BOOLEAN NOT NULL DEFAULT TRUE,
        revoked_at TIMESTAMPTZ,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT uniq_user_version UNIQUE (username, key_version)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS secure_data (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username VARCHAR(100) NOT NULL,
        key_version INTEGER NOT NULL,
        ciphertext TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS secure_data_user_id_idx
    ON secure_data (username, id DESC)
    """,
)


class Command(BaseCommand):
    help = "Create the key-management tables if they do not exist."

    def handle(self, *args, **options):
        connection = get_connection()
        try:
            with connection.cursor() as cursor:
                for statement in SCHEMA_STATEMENTS:
                    cursor.execute(statement)
        finally:
            connection.close()

        self.stdout.write(self.style.SUCCESS("Key-management database schema is ready."))
